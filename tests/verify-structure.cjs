'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html', 'utf8');
const css = fs.readFileSync('styles.css', 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
assert.equal(new Set(ids).size, ids.length, 'HTML IDs are unique');
for (const file of ['styles.css', 'game.js']) assert.ok(fs.existsSync(file), `${file} exists`);
for (const ref of ['styles.css', 'game.js']) assert.match(html, new RegExp(ref.replace('.', '\\.'), 'i'), `${ref} is referenced`);
const game = fs.readFileSync('game.js', 'utf8');
for (const [, id] of game.matchAll(/\$\('([^']+)'\)/g)) assert.ok(ids.includes(id), `game control #${id} exists in HTML`);
for (const landmark of ['<header', '<main', '<footer']) assert.ok(html.includes(landmark), `${landmark} landmark exists`);
for (const view of ['home-view', 'quiz-view', 'study-view', 'results-view']) assert.ok(ids.includes(view), `${view} exists`);
assert.match(css, /@media\s*\(max-width:\s*520px\)/, 'small-screen layout is defined');
assert.match(css, /:focus-visible/, 'keyboard focus is visible');
assert.match(css, /prefers-reduced-motion/, 'reduced motion is supported');
assert.match(html, /aria-live="polite"/, 'live feedback region exists');
assert.doesNotMatch(html, /<img\b/, 'no unprovided external images are required');
console.log(`PASS: HTML structure, ${ids.length} unique IDs, JavaScript references, responsive and accessibility hooks.`);
